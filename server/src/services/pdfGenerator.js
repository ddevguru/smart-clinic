const PDFDocument = require('pdfkit');
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const { storageDir } = require('../config/env');

async function generatePrescriptionPdf(prescriptionData) {
  return new Promise((resolve, reject) => {
    try {
      const dir = path.join(storageDir, 'prescriptions');
      if (!fs.existsSync(dir)) {
        fs.mkdirSync(dir, { recursive: true });
      }

      const fileName = `rx_${prescriptionData.prescription_number}_v${prescriptionData.version_number}.pdf`;
      const filePath = path.join(dir, fileName);
      const writeStream = fs.createWriteStream(filePath);

      const doc = new PDFDocument({ size: 'A4', margin: 40 });
      doc.pipe(writeStream);

      // Header Banner (Mint/Teal Accent)
      doc.rect(40, 40, 515, 60).fill('#087F79');
      doc.fillColor('#FFFFFF').fontSize(18).text(prescriptionData.clinic_name || 'Smart Clinic OS', 55, 52);
      doc.fontSize(9).text(`${prescriptionData.clinic_address || 'Clinic Address'} | Phone: ${prescriptionData.clinic_phone || 'N/A'}`, 55, 75);

      // Doctor Details
      doc.fillColor('#183B3A').fontSize(12).text(prescriptionData.doctor_name || 'Dr. Assigned', 40, 115);
      doc.fontSize(9).fillColor('#666666')
        .text(`${prescriptionData.qualification || 'MBBS'} | Reg No: ${prescriptionData.registration_number || 'KMC-REG'}`, 40, 130)
        .text(`Specialty: ${prescriptionData.specialty || 'General Medicine'}`, 40, 143);

      doc.moveTo(40, 160).lineTo(555, 160).strokeColor('#BFEDE5').stroke();

      // Patient Details Row
      doc.fillColor('#183B3A').fontSize(10)
        .text(`Patient: ${prescriptionData.patient_name}`, 40, 170)
        .text(`Gender/Age: ${prescriptionData.gender || 'N/A'} / ${prescriptionData.age || 'N/A'}`, 240, 170)
        .text(`Date: ${prescriptionData.date || new Date().toLocaleDateString('en-IN')}`, 430, 170)
        .text(`Rx #: ${prescriptionData.prescription_number}`, 40, 185)
        .text(`Contact: ${prescriptionData.patient_phone || 'N/A'}`, 240, 185)
        .text(`Blood Group: ${prescriptionData.blood_group || 'N/A'}`, 430, 185);

      doc.moveTo(40, 205).lineTo(555, 205).strokeColor('#E3EEEB').stroke();

      // Clinical Diagnosis
      let y = 220;
      doc.fillColor('#087F79').fontSize(11).text('CHIEF COMPLAINTS & DIAGNOSIS', 40, y);
      y += 18;
      doc.fillColor('#333333').fontSize(9)
        .text(`Chief Complaints: ${prescriptionData.chief_complaints || 'None reported'}`, 40, y);
      y += 14;
      doc.text(`Provisional Diagnosis: ${prescriptionData.diagnosis || 'Clinical evaluation'}`, 40, y);
      y += 24;

      // Rx Symbol & Medications Table
      doc.fillColor('#087F79').fontSize(14).text('Rx (Medications)', 40, y);
      y += 20;

      // Table Header
      doc.rect(40, y, 515, 20).fill('#F5FAF9');
      doc.fillColor('#183B3A').fontSize(9)
        .text('Medicine / Generic Name', 45, y + 5)
        .text('Dosage & Route', 230, y + 5)
        .text('Frequency & Duration', 350, y + 5)
        .text('Instructions', 460, y + 5);

      y += 25;
      doc.fillColor('#333333').fontSize(9);

      const meds = prescriptionData.medications || [];
      if (meds.length === 0) {
        doc.text('No medications prescribed.', 45, y);
        y += 20;
      } else {
        meds.forEach((m, idx) => {
          doc.text(`${idx + 1}. ${m.medicine_name || m.brand_name || 'Medicine'}`, 45, y);
          doc.text(`${m.dosage || '1 tab'} (${m.route || 'Oral'})`, 230, y);
          doc.text(`${m.frequency || '1-0-1'} for ${m.duration || '5 days'}`, 350, y);
          doc.text(`${m.timing_instructions || m.food_instructions || 'After meals'}`, 460, y);
          y += 20;
        });
      }

      y += 15;
      doc.moveTo(40, y).lineTo(555, y).strokeColor('#E3EEEB').stroke();
      y += 15;

      // Advice & Instructions
      if (prescriptionData.advice_and_precautions) {
        doc.fillColor('#087F79').fontSize(10).text('Advice & Lifestyle Modifications:', 40, y);
        y += 15;
        doc.fillColor('#444444').fontSize(9).text(prescriptionData.advice_and_precautions, 40, y, { width: 515 });
        y += 30;
      }

      // Next Follow-up
      if (prescriptionData.follow_up_date) {
        doc.fillColor('#183B3A').fontSize(10)
          .text(`Next Follow-up: ${prescriptionData.follow_up_date}`, 40, y);
        y += 25;
      }

      // Footer: Verification & Digital Hash
      doc.rect(40, 720, 515, 60).fill('#F5FAF9');
      doc.fillColor('#666666').fontSize(8)
        .text(`Verification Token: ${prescriptionData.verification_token || 'VERIFIED'}`, 50, 728)
        .text(`Digitally Generated by Smart Clinic OS in compliance with Indian Telemedicine Guidelines 2020.`, 50, 742)
        .text(`Scan QR code on verification portal to authenticate this prescription record.`, 50, 756);

      doc.end();

      writeStream.on('finish', () => {
        // Calculate SHA-256 Checksum
        const fileBuffer = fs.readFileSync(filePath);
        const hashSum = crypto.createHash('sha256');
        hashSum.update(fileBuffer);
        const checksum = hashSum.digest('hex');

        resolve({
          fileName,
          filePath,
          storageKey: `prescriptions/${fileName}`,
          checksum
        });
      });

      writeStream.on('error', (err) => reject(err));
    } catch (err) {
      reject(err);
    }
  });
}

module.exports = {
  generatePrescriptionPdf
};

